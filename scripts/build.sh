#!/usr/bin/env bash
# =====================================================================
#  Сборка модели: core и mart с нуля из уже загруженного raw.
#
#      bash scripts/build.sh
#
#  raw не трогает. Порядок файлов задан явно в model/build.sql, сборка
#  идёт одной транзакцией: при ошибке core и mart остаются как были,
#  код возврата ненулевой. Повторный запуск на том же raw даёт тот же
#  результат.
# =====================================================================

set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

db_up

started=$(date +%s)
echo "==> Собираю core и mart (model/build.sql)"
psql_run -f model/build.sql \
  || die "сборка упала, core и mart не изменены" \
         "Ошибка с файлом и строкой — выше."

echo "    ок: собрано за $(( $(date +%s) - started )) с"
